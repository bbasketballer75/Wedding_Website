#!/usr/bin/env node
/**
 * Generates the greenfield rebuild's static SEO/PWA artifacts from the single
 * canonical route-metadata table (`src/app/seo/routeMeta.json`):
 *
 *   public/sitemap.xml          (public, indexable routes only -- no /people)
 *   public/robots.txt           (allows public routes, blocks admin/guest/print)
 *   public/manifest.webmanifest (PWA manifest, real icons under /images/icons/)
 *   public/sw.js                (versioned service worker, safe caching policy)
 *
 * `--check` writes nothing: it verifies the committed artifacts (and the `dist/`
 * copies when a build exists) are byte-identical to what this script would
 * generate, and cross-checks the route table against `contracts/seo-pwa.json`.
 * That is the drift gate CI/the Lead runs after every contract change.
 *
 * Usage:
 *   node scripts/generate-sitemap.mjs [--check] [--site-url URL] [--out DIR] [--dist DIR]
 *
 * Exit codes: 0 ok; 1 drift/contract mismatch; 2 setup error.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import console from 'node:console'
import process from 'node:process'
import path from 'node:path'
import { fileURLToPath, URL } from 'node:url'

const REBUILD_ROOT = fileURLToPath(new URL('..', import.meta.url))
const REPO_ROOT = path.resolve(REBUILD_ROOT, '..')
const ROUTE_META_PATH = path.join(REBUILD_ROOT, 'src/app/seo/routeMeta.json')
const CONTRACT_PATH = path.join(REPO_ROOT, 'contracts/seo-pwa.json')

const FROZEN_ARTIFACT_PATHS = ['sitemap.xml', 'robots.txt', 'manifest.webmanifest', 'sw.js']

function parseArgs(argv) {
  const options = { check: false, siteUrl: undefined, out: 'public', dist: 'dist', help: false }
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index]
    if (arg === '--check') options.check = true
    else if (arg === '--site-url') options.siteUrl = argv[(index += 1)]
    else if (arg === '--out') options.out = argv[(index += 1)]
    else if (arg === '--dist') options.dist = argv[(index += 1)]
    else if (arg === '--help' || arg === '-h') options.help = true
    else throw new Error(`Unknown argument: ${arg}`)
  }
  return options
}

function readJson(filePath) {
  return JSON.parse(readFileSync(filePath, 'utf8'))
}

function normalizeSiteUrl(value) {
  return String(value).replace(/\/+$/, '')
}

function escapeXml(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

/** sitemap.xml -- contract order, no lastmod (deterministic builds). */
export function buildSitemapXml(meta, siteUrl) {
  const entries = meta.sitemap
    .map(entry => {
      const loc = `${siteUrl}${entry.path === '/' ? '/' : entry.path}`
      return [
        '  <url>',
        `    <loc>${escapeXml(loc)}</loc>`,
        `    <changefreq>${entry.changefreq}</changefreq>`,
        `    <priority>${entry.priority.toFixed(1)}</priority>`,
        '  </url>',
      ].join('\n')
    })
    .join('\n')
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${entries}\n</urlset>\n`
}

/** robots.txt -- public routes allowed; admin, guest albums and noindex routes blocked. */
export function buildRobotsTxt(meta, siteUrl) {
  const lines = [
    '# Generated by scripts/generate-sitemap.mjs from src/app/seo/routeMeta.json.',
    '# Do not edit by hand -- run `node scripts/generate-sitemap.mjs`.',
    'User-agent: *',
  ]
  for (const allow of meta.robots.allow) lines.push(`Allow: ${allow}`)
  for (const disallow of meta.robots.disallow) lines.push(`Disallow: ${disallow}`)
  lines.push('', `Sitemap: ${siteUrl}${meta.robots.sitemapPath}`, '')
  return lines.join('\n')
}

/**
 * Canonical JSON formatting matching Prettier's `json` parser output for this
 * document: two-space indentation, one object property per line, object arrays
 * expanded, and short primitive arrays kept inline ("fill" style, printWidth
 * 100). Keeping the generator in sync means the manifest is Prettier-clean
 * without a formatter step in the build; `--check` fails if this ever drifts.
 */
const PRINT_WIDTH = 100

function formatJsonValue(value, indent, column) {
  const pad = ' '.repeat(indent)
  const childPad = ' '.repeat(indent + 2)
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]'
    const isPrimitive = value.every(item => item === null || typeof item !== 'object')
    if (isPrimitive) {
      const inline = `[${value.map(item => JSON.stringify(item)).join(', ')}]`
      if (column + inline.length <= PRINT_WIDTH) return inline
    }
    const items = value.map(item => `${childPad}${formatJsonValue(item, indent + 2, indent + 2)}`)
    return `[\n${items.join(',\n')}\n${pad}]`
  }
  if (value !== null && typeof value === 'object') {
    const keys = Object.keys(value)
    if (keys.length === 0) return '{}'
    const entries = keys.map(key => {
      const prefix = `${childPad}${JSON.stringify(key)}: `
      return `${prefix}${formatJsonValue(value[key], indent + 2, prefix.length)}`
    })
    return `{\n${entries.join(',\n')}\n${pad}}`
  }
  return JSON.stringify(value)
}

export function buildManifestJson(meta) {
  return `${formatJsonValue(meta.manifest, 0, 0)}\n`
}

/**
 * Versioned service worker. Written as pre-formatted lines so the generated
 * file is Prettier-clean without running a formatter in the build.
 */
export function buildServiceWorker(meta) {
  const { serviceWorker } = meta
  const precache = serviceWorker.precache.map(url => `  '${url}',`).join('\n')
  const excluded = serviceWorker.excludedPathPrefixes.map(prefix => `  '${prefix}',`).join('\n')
  const lines = [
    '/**',
    ' * Generated by scripts/generate-sitemap.mjs from src/app/seo/routeMeta.json.',
    ' * Do not edit by hand -- edit the route table and re-run the generator.',
    ' *',
    ' * Caching policy:',
    ' * - precache the static HTML shells + manifest/icons/OG image at install',
    ' * - cache-first for immutable hashed assets (/assets/) and local media/fonts',
    ' * - network-first for navigations with the cached shell as offline fallback',
    ' * - never intercept or cache admin/guest/API/auth routes, cross-origin',
    ' *   requests, or this worker itself',
    ' */',
    `const CACHE_VERSION = '${serviceWorker.version}'`,
    "const CACHE_PREFIX = 'aj-archive-'",
    'const SHELL_CACHE = `${CACHE_PREFIX}shell-${CACHE_VERSION}`',
    'const RUNTIME_CACHE = `${CACHE_PREFIX}runtime-${CACHE_VERSION}`',
    'const PRECACHE_URLS = [',
    precache,
    ']',
    `const OFFLINE_FALLBACK_URL = '${serviceWorker.offlineFallback}'`,
    'const EXCLUDED_PATH_PREFIXES = [',
    excluded,
    ']',
    "const RUNTIME_CACHEABLE_PREFIXES = ['/assets/', '/images/', '/fonts/']",
    '',
    'function isExcludedPath(pathname) {',
    '  return EXCLUDED_PATH_PREFIXES.some(prefix => pathname.startsWith(prefix))',
    '}',
    '',
    'function isRuntimeCacheable(pathname) {',
    '  return RUNTIME_CACHEABLE_PREFIXES.some(prefix => pathname.startsWith(prefix))',
    '}',
    '',
    "self.addEventListener('install', event => {",
    '  event.waitUntil(',
    '    (async () => {',
    '      const cache = await caches.open(SHELL_CACHE)',
    '      await Promise.all(',
    '        PRECACHE_URLS.map(url =>',
    "          cache.add(new Request(url, { cache: 'reload' })).catch(() => undefined)",
    '        )',
    '      )',
    '      await self.skipWaiting()',
    '    })()',
    '  )',
    '})',
    '',
    "self.addEventListener('activate', event => {",
    '  event.waitUntil(',
    '    (async () => {',
    '      const keys = await caches.keys()',
    '      await Promise.all(',
    '        keys',
    '          .filter(',
    '            key => key.startsWith(CACHE_PREFIX) && key !== SHELL_CACHE && key !== RUNTIME_CACHE',
    '          )',
    '          .map(key => caches.delete(key))',
    '      )',
    '      await self.clients.claim()',
    '    })()',
    '  )',
    '})',
    '',
    "self.addEventListener('fetch', event => {",
    '  const { request } = event',
    "  if (request.method !== 'GET') return",
    '',
    '  const url = new URL(request.url)',
    '  if (url.origin !== self.location.origin) return',
    '  if (isExcludedPath(url.pathname)) return',
    '',
    "  if (request.mode === 'navigate') {",
    '    event.respondWith(',
    '      (async () => {',
    '        try {',
    '          return await fetch(request)',
    '        } catch {',
    '          const cache = await caches.open(SHELL_CACHE)',
    '          const cached = await cache.match(request)',
    '          if (cached) return cached',
    '          const fallback = await cache.match(OFFLINE_FALLBACK_URL)',
    '          return fallback ?? Response.error()',
    '        }',
    '      })()',
    '    )',
    '    return',
    '  }',
    '',
    '  if (!isRuntimeCacheable(url.pathname)) return',
    '',
    '  event.respondWith(',
    '    (async () => {',
    '      const cache = await caches.open(RUNTIME_CACHE)',
    '      const cached = await cache.match(request)',
    '      if (cached) return cached',
    '      const response = await fetch(request)',
    "      if (response.ok && response.type === 'basic') {",
    '        await cache.put(request, response.clone())',
    '      }',
    '      return response',
    '    })()',
    '  )',
    '})',
    '',
  ]
  return lines.join('\n')
}

/** The four files this generator owns, keyed by file name. */
export function expectedArtifacts(meta, siteUrl) {
  return {
    'sitemap.xml': buildSitemapXml(meta, siteUrl),
    'robots.txt': buildRobotsTxt(meta, siteUrl),
    'manifest.webmanifest': buildManifestJson(meta),
    'sw.js': buildServiceWorker(meta),
  }
}

/**
 * Cross-checks the canonical route table against the tracked contracts. The
 * contract layer is the source of truth for frozen routes; wave8-fix and
 * wave8-shell entries are documented repairs (see routeMeta.json notes).
 */
export function validateContracts(meta, contractPath = CONTRACT_PATH) {
  const problems = []
  if (!existsSync(contractPath)) {
    return { problems, skipped: 'contracts/seo-pwa.json not found (decoupled run)' }
  }
  const contract = readJson(contractPath)

  const byId = new Map(meta.routes.map(route => [route.id, route]))
  for (const contractRoute of contract.routes) {
    const route = byId.get(contractRoute.id)
    if (!route) {
      problems.push(`routeMeta.json is missing contract route "${contractRoute.id}"`)
      continue
    }
    for (const field of ['title', 'description', 'robots']) {
      // The guest-token contract is a runtime template (`<guest name>`); the
      // static shell ships generic build-time copy (source: wave8-shell).
      if (route.source === 'wave8-shell' && (field === 'title' || field === 'description')) continue
      if (contractRoute[field] !== undefined && route[field] !== contractRoute[field]) {
        problems.push(
          `route "${contractRoute.id}" ${field}: routeMeta=${JSON.stringify(route[field])} contract=${JSON.stringify(contractRoute[field])}`
        )
      }
    }
    if (
      contractRoute.canonicalPath !== undefined &&
      route.source !== 'wave8-shell' &&
      route.canonicalPath !== contractRoute.canonicalPath
    ) {
      problems.push(
        `route "${contractRoute.id}" canonicalPath: routeMeta=${JSON.stringify(route.canonicalPath)} contract=${JSON.stringify(contractRoute.canonicalPath)}`
      )
    }
    if (
      route.source === undefined &&
      contractRoute.ogImage !== undefined &&
      route.ogImage !== contractRoute.ogImage
    ) {
      problems.push(
        `route "${contractRoute.id}" ogImage: routeMeta=${JSON.stringify(route.ogImage)} contract=${JSON.stringify(contractRoute.ogImage)}`
      )
    }
  }

  const contractSitemap = JSON.stringify(contract.sitemap)
  if (JSON.stringify(meta.sitemap) !== contractSitemap) {
    problems.push('sitemap entries differ from contracts/seo-pwa.json')
  }

  for (const key of [
    'name',
    'short_name',
    'display',
    'start_url',
    'theme_color',
    'background_color',
    'lang',
  ]) {
    if (meta.manifest[key] !== contract.manifest[key]) {
      problems.push(
        `manifest.${key}: routeMeta=${JSON.stringify(meta.manifest[key])} contract=${JSON.stringify(contract.manifest[key])}`
      )
    }
  }
  return { problems }
}

function compareArtifacts(expected, directories) {
  const drift = []
  for (const directory of directories) {
    if (!directory) continue
    for (const name of FROZEN_ARTIFACT_PATHS) {
      const filePath = path.join(directory.dir, name)
      if (!existsSync(filePath)) {
        drift.push(`${directory.label}/${name} is missing`)
        continue
      }
      const actual = readFileSync(filePath, 'utf8')
      if (actual !== expected[name]) {
        drift.push(`${directory.label}/${name} differs from the generated output`)
      }
    }
  }
  return drift
}

/** Every manifest icon must exist as a real file in the served public tree. */
function missingManifestIcons(meta, directory) {
  const icons = [
    ...meta.manifest.icons,
    ...meta.manifest.shortcuts.flatMap(shortcut => shortcut.icons ?? []),
  ]
  const missing = []
  for (const icon of icons) {
    const filePath = path.join(directory, icon.src.replace(/^\//, ''))
    if (!existsSync(filePath)) missing.push(icon.src)
  }
  return missing
}

function writeArtifacts(artifacts, directory) {
  mkdirSync(directory, { recursive: true })
  for (const name of FROZEN_ARTIFACT_PATHS) {
    writeFileSync(path.join(directory, name), artifacts[name], 'utf8')
  }
}

function main(argv) {
  const options = parseArgs(argv)
  if (options.help) {
    console.log(
      'Usage: node scripts/generate-sitemap.mjs [--check] [--site-url URL] [--out DIR] [--dist DIR]'
    )
    return 0
  }

  const meta = readJson(ROUTE_META_PATH)
  const siteUrl = normalizeSiteUrl(options.siteUrl ?? meta.siteUrl)
  const artifacts = expectedArtifacts(meta, siteUrl)

  const contractCheck = validateContracts(meta)
  if (contractCheck.problems.length > 0) {
    console.error('Contract drift in src/app/seo/routeMeta.json:')
    for (const problem of contractCheck.problems) console.error(`  - ${problem}`)
    return 1
  }
  if (contractCheck.skipped) console.warn(`note: ${contractCheck.skipped}`)

  const outDir = path.resolve(REBUILD_ROOT, options.out)
  const distDir = path.resolve(REBUILD_ROOT, options.dist)
  const directories = [{ dir: outDir, label: options.out }]
  if (existsSync(path.join(distDir, 'index.html'))) {
    directories.push({ dir: distDir, label: options.dist })
  }

  const missingIcons = directories.flatMap(directory =>
    missingManifestIcons(meta, directory.dir).map(src => `${directory.label}${src}`)
  )
  if (missingIcons.length > 0) {
    console.error('Manifest icons are missing from the served tree:')
    for (const item of missingIcons) console.error(`  - ${item}`)
    return 1
  }

  if (options.check) {
    const drift = compareArtifacts(artifacts, directories)
    if (drift.length > 0) {
      console.error('Generated SEO/PWA artifacts are stale:')
      for (const item of drift) console.error(`  - ${item}`)
      console.error('Run `node scripts/generate-sitemap.mjs` and commit the result.')
      return 1
    }
    console.log(
      `check ok: ${directories.map(directory => directory.label).join(', ')} match the route table (${meta.routes.length} routes, ${meta.sitemap.length} sitemap entries, all manifest icons present)`
    )
    return 0
  }

  writeArtifacts(artifacts, outDir)
  for (const directory of directories) {
    if (directory.dir !== outDir) writeArtifacts(artifacts, directory.dir)
  }
  console.log(
    `wrote ${FROZEN_ARTIFACT_PATHS.join(', ')} to ${directories.map(directory => directory.label).join(', ')}`
  )
  console.log(
    `  ${meta.sitemap.length} sitemap entries, ${meta.manifest.icons.length} manifest icons, service worker ${meta.serviceWorker.version}`
  )
  return 0
}

const invokedDirectly =
  process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (invokedDirectly) {
  try {
    process.exitCode = main(process.argv.slice(2))
  } catch (error) {
    console.error(
      `generate-sitemap failed: ${error instanceof Error ? error.message : String(error)}`
    )
    process.exitCode = 2
  }
}
